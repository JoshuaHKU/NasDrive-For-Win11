/// <summary>
/// Runtime switchable string table. XAML binds with
/// <c>{Binding [Key], Source={x:Static svc:Loc.Instance}}</c>.
/// </summary>
public sealed class Loc : INotifyPropertyChanged
{
    public static Loc Instance { get; } = new();

    public event PropertyChangedEventHandler? PropertyChanged;

    public string Language { get; private set; } = "zh-CN";

    public string this[string key] => Lookup(key);

    public static string T(string key, params object[] args)
    {
        var s = Instance.Lookup(key);
        return args.Length == 0 ? s : string.Format(s, args);
    }

    public void SetLanguage(string? lang)
    {
        if (string.IsNullOrEmpty(lang))
            lang = CultureInfo.CurrentUICulture.Name.StartsWith("zh") ? "zh-CN" : "en-US";
        Language = lang == "en-US" ? "en-US" : "zh-CN";
        PropertyChanged?.Invoke(this, new PropertyChangedEventArgs("Item[]"));
        PropertyChanged?.Invoke(this, new PropertyChangedEventArgs(nameof(Language)));
    }

    private string Lookup(string key)
    {
        var table = Language == "en-US" ? En : Zh;
        if (table.TryGetValue(key, out var v)) return v;
        return Zh.TryGetValue(key, out v) ? v : key;
    }

